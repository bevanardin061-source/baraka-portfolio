create table if not exists public.frames(
  id bigint generated by default as identity primary key,
  src text not null,
  w int not null default 1000,
  h int not null default 1400,
  cat text not null default 'studio',
  title text not null default 'Photo',
  sort bigint not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.site_settings(
  id int primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb
);

-- Only Baraka's verified Google account counts as the owner.
create or replace function public.is_owner() returns boolean
language sql stable as $$
  select lower(coalesce(auth.jwt() ->> 'email','')) = 'barakajowi91@gmail.com'
     and coalesce((auth.jwt() -> 'user_metadata' ->> 'email_verified')::boolean, false)
$$;

alter table public.frames enable row level security;
alter table public.site_settings enable row level security;

drop policy if exists "frames read" on public.frames;
drop policy if exists "frames add" on public.frames;
drop policy if exists "frames edit" on public.frames;
drop policy if exists "frames delete" on public.frames;
create policy "frames read"   on public.frames for select using (true);
create policy "frames add"    on public.frames for insert with check (public.is_owner());
create policy "frames edit"   on public.frames for update using (public.is_owner()) with check (public.is_owner());
create policy "frames delete" on public.frames for delete using (public.is_owner());

drop policy if exists "settings read" on public.site_settings;
drop policy if exists "settings add" on public.site_settings;
drop policy if exists "settings edit" on public.site_settings;
create policy "settings read" on public.site_settings for select using (true);
create policy "settings add"  on public.site_settings for insert with check (public.is_owner());
create policy "settings edit" on public.site_settings for update using (public.is_owner()) with check (public.is_owner());

grant select on public.frames, public.site_settings to anon, authenticated;
grant insert, update, delete on public.frames to authenticated;
grant insert, update on public.site_settings to authenticated;
grant usage, select on sequence public.frames_id_seq to authenticated;

-- Photo storage (public to read, owner-only to change)
insert into storage.buckets (id, name, public) values ('frames','frames',true) on conflict (id) do update set public = true;
drop policy if exists "frames files read" on storage.objects;
drop policy if exists "frames files add" on storage.objects;
drop policy if exists "frames files edit" on storage.objects;
drop policy if exists "frames files delete" on storage.objects;
create policy "frames files read"   on storage.objects for select using (bucket_id = 'frames');
create policy "frames files add"    on storage.objects for insert with check (bucket_id = 'frames' and public.is_owner());
create policy "frames files edit"   on storage.objects for update using (bucket_id = 'frames' and public.is_owner());
create policy "frames files delete" on storage.objects for delete using (bucket_id = 'frames' and public.is_owner());

